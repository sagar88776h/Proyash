#!/usr/bin/env node
// Generates src/types/database.ts from the migrated local database, in the
// same shape as `supabase gen types typescript`. With a linked Supabase
// project you can use the official CLI instead:
//   npx supabase gen types typescript --project-id <id> --schema public > src/types/database.ts
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import pg from 'pg';
import { DB_URL, ROOT } from './local-stack/config.mjs';

const client = new pg.Client({ connectionString: process.env.DATABASE_URL ?? DB_URL });
await client.connect();

const enums = (
  await client.query(`
    select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows;
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt, isArray = false) {
  const base = udt.replace(/^_/, '');
  let t;
  if (enumNames.has(base)) t = `Database['public']['Enums']['${base}']`;
  else if (['int2', 'int4', 'int8', 'float4', 'float8', 'numeric'].includes(base)) t = 'number';
  else if (base === 'bool') t = 'boolean';
  else if (['json', 'jsonb'].includes(base)) t = 'Json';
  else if (base === 'void') t = 'undefined';
  else t = 'string';
  return isArray || udt.startsWith('_') ? `${t}[]` : t;
}

const columns = (
  await client.query(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
           c.column_default is not null as has_default, c.is_identity = 'YES' as is_identity,
           c.is_generated = 'ALWAYS' as is_generated, c.identity_generation, c.ordinal_position
    from information_schema.columns c
    join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position`)
).rows;

const fks = (
  await client.query(`
    select con.conname, cl.relname as table_name, rcl.relname as ref_table,
           array(select a.attname::text from unnest(con.conkey) with ordinality k(attnum, ord)
                 join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum order by k.ord) as columns,
           array(select a.attname::text from unnest(con.confkey) with ordinality k(attnum, ord)
                 join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.attnum order by k.ord) as ref_columns,
           exists (
             select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique
               and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x) = (select array_agg(x order by x) from unnest(con.conkey) x)
           ) as one_to_one,
           rn.nspname as ref_schema
    from pg_constraint con
    join pg_class cl on cl.oid = con.conrelid join pg_namespace n on n.oid = cl.relnamespace
    join pg_class rcl on rcl.oid = con.confrelid join pg_namespace rn on rn.oid = rcl.relnamespace
    where con.contype = 'f' and n.nspname = 'public'
    order by con.conname`)
).rows;

const functions = (
  await client.query(`
    select p.proname as name, p.proretset as returns_set, rt.typname as return_type, p.proargnames::text[] as arg_names,
           p.proargmodes::text[] as arg_modes,
           array(select t.typname::text from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality as a(oid, ord) join pg_type t on t.oid = a.oid order by a.ord) as arg_types,
           p.pronargs as nargs, p.pronargdefaults as ndefaults
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
    where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
    order by p.proname`)
).rows;

const tables = [...new Set(columns.map((c) => c.table_name))].sort();
const out = [];
out.push('// Generated by scripts/gen-db-types.mjs from the migrated database. Do not edit by hand.');
out.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];');
out.push('');
out.push('export type Database = {');
out.push('  public: {');
out.push('    Tables: {');
for (const table of tables) {
  const cols = columns.filter((c) => c.table_name === table);
  out.push(`      ${table}: {`);
  out.push('        Row: {');
  for (const c of cols) out.push(`          ${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''};`);
  out.push('        };');
  for (const kind of ['Insert', 'Update']) {
    out.push(`        ${kind}: {`);
    for (const c of cols) {
      if (c.is_generated || c.identity_generation === 'ALWAYS') {
        out.push(`          ${c.column_name}?: never;`);
        continue;
      }
      const optional = kind === 'Update' || c.nullable || c.has_default || c.is_identity;
      out.push(`          ${c.column_name}${optional ? '?' : ''}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''};`);
    }
    out.push('        };');
  }
  out.push('        Relationships: [');
  for (const fk of fks.filter((f) => f.table_name === table && f.ref_schema === 'public')) {
    out.push('          {');
    out.push(`            foreignKeyName: '${fk.conname}';`);
    out.push(`            columns: [${fk.columns.map((c) => `'${c}'`).join(', ')}];`);
    out.push(`            isOneToOne: ${fk.one_to_one};`);
    out.push(`            referencedRelation: '${fk.ref_table}';`);
    out.push(`            referencedColumns: [${fk.ref_columns.map((c) => `'${c}'`).join(', ')}];`);
    out.push('          },');
  }
  out.push('        ];');
  out.push('      };');
}
out.push('    };');
out.push('    Views: { [_ in never]: never };');
out.push('    Functions: {');
for (const fn of functions) {
  const names = fn.arg_names ?? [];
  const modes = fn.arg_modes ?? names.map(() => 'i');
  const types = fn.arg_types ?? [];
  const inputs = [];
  const outputs = [];
  names.forEach((n, i) => {
    const mode = modes[i] ?? 'i';
    if (mode === 'i' || mode === 'b') inputs.push({ name: n, type: types[i] });
    if (mode === 't' || mode === 'o' || mode === 'b') outputs.push({ name: n, type: types[i] });
  });
  const firstDefault = inputs.length - fn.ndefaults;
  out.push(`      ${fn.name}: {`);
  if (inputs.length === 0) out.push('        Args: Record<PropertyKey, never>;');
  else {
    out.push('        Args: {');
    inputs.forEach((a, i) => out.push(`          ${a.name}${i >= firstDefault ? '?' : ''}: ${tsType(a.type)} | null;`));
    out.push('        };');
  }
  let ret;
  if (outputs.length) ret = `{ ${outputs.map((o) => `${o.name}: ${tsType(o.type)} | null`).join('; ')} }[]`;
  else ret = tsType(fn.return_type, fn.returns_set);
  out.push(`        Returns: ${ret};`);
  out.push('      };');
}
out.push('    };');
out.push('    Enums: {');
for (const e of enums) out.push(`      ${e.name}: ${e.labels.map((l) => `'${l}'`).join(' | ')};`);
out.push('    };');
out.push('    CompositeTypes: { [_ in never]: never };');
out.push('  };');
out.push('};');
out.push('');
out.push("type PublicSchema = Database['public'];");
out.push("export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row'];");
out.push("export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert'];");
out.push("export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update'];");
out.push("export type Enums<T extends keyof PublicSchema['Enums']> = PublicSchema['Enums'][T];");
out.push("export type FunctionArgs<T extends keyof PublicSchema['Functions']> = PublicSchema['Functions'][T]['Args'];");
out.push("export type FunctionReturns<T extends keyof PublicSchema['Functions']> = PublicSchema['Functions'][T]['Returns'];");
out.push('');

const file = join(ROOT, 'src', 'types', 'database.ts');
writeFileSync(file, out.join('\n'));
await client.end();
console.log(`wrote ${file} (${tables.length} tables, ${functions.length} functions, ${enums.length} enums)`);
